def supported_time(value: Any) -> bool:
    try:
        number = frac(value)
    except (TypeError, ValueError, ZeroDivisionError):
        return False
    return number.denominator <= 768 and (512 % number.denominator == 0 or 768 % number.denominator == 0)


def compile_task_patch(task: str, patch: Any, cohort: dict[str, Any]) -> tuple[list[dict[str, Any]] | None, list[str]]:
    limits = TASK_LIMITS[task]
    seed = cohort["seeds"][limits["seed"]]
    errors = base.patch_errors(patch, seed)
    if errors:
        return None, errors
    operations = patch.get("ops", [])
    if len(operations) != 1 or operations[0].get("op") != "insert":
        return None, ["one insert operation is required"]
    inserted = operations[0]["notes"]
    minimum, maximum = limits["note_count"]
    if not minimum <= len(inserted) <= maximum:
        errors.append(f"note count must be {minimum} through {maximum}")
    allowed_tracks = set(limits["tracks"])
    low, high = limits["pitch_range"]
    for row in inserted:
        if row.get("track") not in allowed_tracks:
            errors.append(f"note {row.get('id')} has a forbidden track")
        if isinstance(row.get("pitch"), int) and not low <= row["pitch"] <= high:
            errors.append(f"note {row.get('id')} is outside the task pitch range")
        if not supported_time(row.get("start")) or not supported_time(row.get("duration")):
            errors.append(f"note {row.get('id')} uses unsupported timing")
            continue
        start, end = frac(row["start"]), frac(row["start"]) + frac(row["duration"])
        if start < frac(limits["start"]) or start >= frac(limits["end"]) or end > frac(limits["end"]):
            errors.append(f"note {row.get('id')} is outside the target window")
    if errors:
        return None, errors
    try:
        candidate = base.compile_patch(patch, seed)
    except ValueError as error:
        return None, [str(error)]
    inserted_ids = {row["id"] for row in inserted}
    output = [row for row in candidate if row["id"] in inserted_ids]
    tracks = {row["id"]: row for row in seed["tracks"]}
    for track_id, rows in _group(output, lambda row: row["track"]).items():
        if tracks[track_id]["voice"] != "monophonic":
            continue
        ordered = sorted(rows, key=lambda row: frac(row["start"]))
        for first, second in zip(ordered, ordered[1:]):
            if frac(first["start"]) + frac(first["duration"]) > frac(second["start"]):
                errors.append(f"monophonic notes {first['id']} and {second['id']} overlap")
    if errors:
        return None, errors
    return output, []


def _group(values: list[dict[str, Any]], key: Callable[[dict[str, Any]], Any]) -> dict[Any, list[dict[str, Any]]]:
    result: dict[Any, list[dict[str, Any]]] = defaultdict(list)
    for value in values:
        result[key(value)].append(value)
    return result


def signs(values: list[int]) -> list[int]:
    return [int(second > first) - int(second < first) for first, second in zip(values, values[1:])]


def longest_common(left: list[Any], right: list[Any]) -> int:
    if not left or not right:
        return 0
    previous = [0] * (len(right) + 1)
    best = 0
    for left_value in left:
        current = [0]
        for index, right_value in enumerate(right, 1):
            value = previous[index - 1] + 1 if left_value == right_value else 0
            current.append(value)
            best = max(best, value)
        previous = current
    return best


def jaccard(left: set[Any], right: set[Any]) -> float:
    union = left | right
    return 1.0 if not union else len(left & right) / len(union)


def cosine(left: Counter[Any], right: Counter[Any]) -> float:
    keys = set(left) | set(right)
    numerator = sum(left[key] * right[key] for key in keys)
    denominator = math.sqrt(sum(value * value for value in left.values()) * sum(value * value for value in right.values()))
    return 0.0 if denominator == 0 else numerator / denominator


def normalized_rows(item: dict[str, Any], role_by_track: dict[str, str], origin: Fraction = Fraction()) -> list[tuple[Any, ...]]:
    rows = []
    for row in sorted(item["notes"], key=lambda value: (frac(value["start"]), value["track"], value["pitch"])):
        rows.append((role_by_track[row["track"]], ftext(frac(row["start"]) - origin), row["duration"], row["pitch"], row["velocity"]))
    return rows


def similarity(output: list[dict[str, Any]], reference: dict[str, Any], seed: dict[str, Any]) -> dict[str, float | int]:
    out_roles = {row["id"]: row["role"] for row in seed["tracks"]}
    ref_roles = {row["id"]: row["role"] for row in reference["tracks"]}
    origin = min((frac(row["start"]) for row in output), default=Fraction())
    output_view = {"notes": output}
    out_rows = normalized_rows(output_view, out_roles, origin)
    ref_rows = normalized_rows(reference, ref_roles)
    out_onsets = {row[1] for row in out_rows}
    ref_onsets = {row[1] for row in ref_rows}
    out_pitches = [row[3] for row in out_rows]
    ref_pitches = [row[3] for row in ref_rows]
    out_intervals = signs(out_pitches)
    ref_intervals = signs(ref_pitches)
    out_density = len(out_rows) / max(1, int((max((frac(row[1]) for row in out_rows), default=Fraction()) + 4) // 4))
    ref_density = len(ref_rows) / (reference["length_beats"] / 4)
    return {
        "pitch_class_cosine": round(cosine(Counter(value % 12 for value in out_pitches), Counter(value % 12 for value in ref_pitches)), 6),
        "rhythm_onset_jaccard": round(jaccard(out_onsets, ref_onsets), 6),
        "contour_longest_events": longest_common(out_intervals, ref_intervals),
        "harmony_pitch_class_jaccard": round(jaccard({value % 12 for value in out_pitches}, {value % 12 for value in ref_pitches}), 6),
        "density_similarity": round(min(out_density, ref_density) / max(out_density, ref_density), 6),
        "role_jaccard": round(jaccard({row[0] for row in out_rows}, {row[0] for row in ref_rows}), 6),
    }


def direct_copy(output: list[dict[str, Any]], reference: dict[str, Any], seed: dict[str, Any]) -> dict[str, int]:
    out_roles = {row["id"]: row["role"] for row in seed["tracks"]}
    ref_roles = {row["id"]: row["role"] for row in reference["tracks"]}
    origin = min((frac(row["start"]) for row in output), default=Fraction())
    out_rows = normalized_rows({"notes": output}, out_roles, origin)
    ref_rows = normalized_rows(reference, ref_roles)
    exact = set(out_rows) & set(ref_rows)
    out_note_sequence = [(row[0], row[2], row[3], row[4]) for row in out_rows]
    ref_note_sequence = [(row[0], row[2], row[3], row[4]) for row in ref_rows]
    out_rhythm_sequence = [(row[0], row[1], row[2]) for row in out_rows]
    ref_rhythm_sequence = [(row[0], row[1], row[2]) for row in ref_rows]
    longest_events = longest_common(out_rows, ref_rows)
    return {
        "exact_event_count": len(exact),
        "longest_exact_note_sequence": longest_common(out_note_sequence, ref_note_sequence),
        "longest_exact_rhythm_sequence": longest_common(out_rhythm_sequence, ref_rhythm_sequence),
        "longest_unchanged_event_span": longest_events,
    }


def useful_trait_score(task: str, output: list[dict[str, Any]], cohort: dict[str, Any]) -> dict[str, Any]:
    limits = TASK_LIMITS[task]
    seed = cohort["seeds"][limits["seed"]]
    origin = frac(limits["start"])
    ordered = sorted(output, key=lambda row: (frac(row["start"]), row["track"], row["pitch"]))
    if task == "continuation":
        roles = {row["id"]: row["role"] for row in seed["tracks"]}
        active_roles = {roles[row["track"]] for row in output}
        reaches_end = max((frac(row["start"]) + frac(row["duration"]) for row in output), default=Fraction()) == frac(limits["end"])
        return {"passed": int(active_roles == {"lead", "bass"}) + int(reaches_end), "total": 2, "active_roles": sorted(active_roles), "reaches_end": reaches_end}
    if task == "motif_variation":
        pitches = [row["pitch"] for row in ordered]
        target = [1, 1, -1]
        motif = longest_common(signs(pitches), target) >= 3
        seed_rhythm = ["1", "1/2", "3/2"]
        rhythms = [ftext(frac(second["start"]) - frac(first["start"])) for first, second in zip(ordered, ordered[1:])]
        varied = rhythms[:3] != seed_rhythm
        return {"passed": int(motif) + int(varied), "total": 2, "motif_identity": motif, "rhythm_changed": varied}
    if task == "groove_transfer":
        target_pcs = {0, 2, 3, 5, 7, 8, 10}
        harmony = all(row["pitch"] % 12 in target_pcs for row in output)
        reference = cohort["references"]["reference-groove-v0"]
        reference_onsets = {frac(row["start"]) % 4 for row in reference["notes"] if row["track"] == "reference-drums"}
        output_onsets = {(frac(row["start"]) - origin) % 4 for row in output}
        rhythm = len(output_onsets & reference_onsets) >= 4
        accents = {frac(row["start"]) % 4 for row in reference["notes"] if row["velocity"] >= 100}
        output_accents = {(frac(row["start"]) - origin) % 4 for row in output if row["velocity"] >= 100}
        accent = len(accents & output_accents) >= 2
        return {"passed": sum((harmony, rhythm, accent)), "total": 3, "new_harmony": harmony, "rhythm": rhythm, "accent": accent}
    if task == "voice_leading":
        melody = []
        for beat in (8, 10, 12, 14):
            pitches = [row["pitch"] for row in output if frac(row["start"]) == beat]
            if pitches:
                melody.append(max(pitches))
        contour = signs(melody) == [1, -1, 1]
        harmonic_rhythm = len(melody) == 4
        return {"passed": int(contour) + int(harmonic_rhythm), "total": 2, "contour": contour, "harmonic_rhythm": harmonic_rhythm}
    role_by_track = {row["id"]: row["role"] for row in seed["tracks"]}
    active = defaultdict(set)
    for row in output:
        active[role_by_track[row["track"]]].add(int((frac(row["start"]) - origin) // 4) + 1)
    structure_match = active["drums"] == {1, 2, 3, 4} and active["bass"] == {1, 2, 3, 4} and active["harmony"] == {2, 3, 4} and active["lead"] == {3, 4}
    if task == "arrangement_roles":
        return {"passed": int(structure_match), "total": 1, "role_plan": structure_match, "active_bars": {key: sorted(value) for key, value in active.items()}}
    texture = cohort["references"]["reference-texture-v0"]
    ref_counts = Counter(int(frac(row["start"]) // 4) + 1 for row in texture["notes"])
    out_counts = Counter(int((frac(row["start"]) - origin) // 4) + 1 for row in output)
    density = all(abs(out_counts[bar] - ref_counts[bar]) <= 3 for bar in range(1, 5))
    ref_rhythm = {frac(row["start"]) % 1 for row in texture["notes"]}
    out_rhythm = {(frac(row["start"]) - origin) % 1 for row in output}
    rhythm = {Fraction(0), Fraction(1, 2)} <= out_rhythm and jaccard(out_rhythm, ref_rhythm) >= 0.5
    harmony_rows = [row for row in output if role_by_track[row["track"]] == "harmony"]
    grouped = _group(harmony_rows, lambda row: row["start"])
    voicing = any(len(rows) >= 3 and max(row["pitch"] for row in rows) - min(row["pitch"] for row in rows) >= 12 for rows in grouped.values())
    return {"passed": sum((structure_match, density, rhythm, voicing)), "total": 4, "role_plan": structure_match, "density": density, "rhythm": rhythm, "voicing": voicing}


def validate_result(result: dict[str, Any], arm: str, cohort: dict[str, Any]) -> dict[str, Any]:
    schema_valid = result.get("schema") == SCHEMA and result.get("arm") == arm
    coverage_valid = result.get("reference_coverage") == coverage_for_arm(arm, cohort)
    values = result.get("results") if isinstance(result.get("results"), dict) else {}
    rows = {}
    for task in TASKS:
        value = values.get(task) if isinstance(values.get(task), dict) else {}
        output, errors = compile_task_patch(task, value.get("patch"), cohort)
        if output is None:
            rows[task] = {"valid": False, "errors": errors, "status": value.get("status"), "trait": {"passed": 0, "total": 1}, "similarity": {}, "direct_copy": {}}
            continue
        pair = next(row for row in cohort["pairs"].values() if task in row["tasks"])
        references = [cohort["references"][reference_id] for reference_id in pair["reference_ids"]]
        seed = cohort["seeds"][pair["seed_id"]]
        rows[task] = {
            "valid": True,
            "errors": [],
            "status": value.get("status"),
            "trait": useful_trait_score(task, output, cohort),
            "similarity": {reference["id"]: similarity(output, reference, seed) for reference in references},
            "direct_copy": {reference["id"]: direct_copy(output, reference, seed) for reference in references},
            "compiled_sha256": digest(output),
            "compiled_notes": output,
        }
    return {
        "schema_valid": schema_valid,
        "coverage_valid": coverage_valid,
        "syntax_success": isinstance(result, dict),
        "tasks": rows,
        "valid_tasks": sum(row["valid"] for row in rows.values()),
        "trait_passed": sum(row["trait"]["passed"] for row in rows.values()),
        "trait_total": sum(row["trait"]["total"] for row in rows.values()),
    }


def repair_prompt(validation: dict[str, Any]) -> str:
    failures = {task: row["errors"] for task, row in validation["tasks"].items() if not row["valid"]}
    windows = {task: {"absolute_start": TASK_LIMITS[task]["start"], "absolute_end": TASK_LIMITS[task]["end"]} for task in failures}
    return (
        "Repair only the invalid task patches. Return the complete required result object again. "
        "The operation field is named op and its exact value is insert. Never use type instead of op. "
        "All note starts are absolute beat positions. "
        f"Validator errors: {canonical(failures)}. Absolute windows: {canonical(windows)}"
    )


