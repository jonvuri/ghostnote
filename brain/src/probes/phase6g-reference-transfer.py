def directory_bytes(path: Path) -> int:
    return sum(item.stat().st_size for item in path.rglob("*") if item.is_file())


def seed_instruments(seed: dict[str, Any]) -> dict[str, int]:
    role_to_instrument = {"lead": 1, "harmony": 5, "bass": 34, "drums": 129}
    roles = {row["id"]: row["role"] for row in seed["tracks"]}
    return {track_id: role_to_instrument[role] for track_id, role in roles.items()}


def feed_seed(model: Any, seed: dict[str, Any]) -> None:
    instruments = seed_instruments(seed)
    events = []
    for row in seed["notes"]:
        events.append((frac(row["start"]), 1, instruments[row["track"]], row["pitch"], row["velocity"]))
        events.append((frac(row["start"]) + frac(row["duration"]), 0, instruments[row["track"]], row["pitch"], 0))
    cursor = Fraction()
    for position, unused_order, instrument, pitch, velocity in sorted(events):
        model.feed(instrument, pitch, float(position - cursor) * 0.5, velocity)
        cursor = position


def notochord_task(model: Any, task: str, cohort: dict[str, Any], run_seed: int) -> tuple[dict[str, Any], dict[str, Any]]:
    import torch

    limits = TASK_LIMITS[task]
    seed = cohort["seeds"][limits["seed"]]
    instruments_by_track = seed_instruments(seed)
    tracks_by_instrument = {instrument: track for track, instrument in instruments_by_track.items() if track in limits["tracks"]}
    allowed_instruments = set(tracks_by_instrument)
    low, high = limits["pitch_range"]
    allowed_pitches = set(range(low, high + 1))
    allowed_drums = set(range(max(35, low), min(51, high) + 1))
    torch.manual_seed(run_seed)
    random.seed(run_seed)
    model.reset()
    feed_seed(model, seed)
    current_seconds = 0.0
    target_seconds = float(frac(limits["end"]) - frac(limits["start"])) * 0.5
    active: dict[tuple[int, int], tuple[Fraction, int]] = {}
    completed = []
    raw_events = []
    quantization_errors = []
    max_notes = limits["note_count"][1]
    for event_index in range(320):
        started = time.perf_counter()
        event = model.query(
            include_inst=allowed_instruments,
            include_pitch=allowed_pitches,
            include_drum=allowed_drums,
            min_time=0.005,
            max_time=min(0.75, max(0.005, target_seconds - current_seconds)),
            min_vel=0,
            max_vel=120,
            allow_end=False,
        )
        query_ms = (time.perf_counter() - started) * 1000
        current_seconds += float(event["time"])
        if current_seconds > target_seconds + 1e-9:
            break
        model.feed(**event)
        exact_beat = frac(limits["start"]) + Fraction(current_seconds * 2).limit_denominator(10**9)
        quantized_beat = Fraction(round(float(exact_beat) * 512), 512)
        quantization_errors.append(abs(float(exact_beat - quantized_beat)))
        instrument, pitch = int(event["inst"]), int(event["pitch"])
        velocity = int(round(float(event["vel"])))
        raw_events.append({"instrument": instrument, "pitch": pitch, "time_seconds": float(event["time"]), "velocity": velocity, "query_ms": query_ms})
        key = (instrument, pitch)
        if velocity > 0 and len(active) + len(completed) < max_notes:
            active[key] = (quantized_beat, max(1, min(127, velocity)))
        elif velocity <= 0 and key in active:
            start, onset_velocity = active.pop(key)
            duration = max(Fraction(1, 512), quantized_beat - start)
            completed.append((instrument, start, duration, pitch, onset_velocity))
        if current_seconds >= target_seconds:
            break
    target_end = frac(limits["end"])
    for (instrument, pitch), (start, onset_velocity) in active.items():
        default_duration = Fraction(1, 8) if instrument >= 129 else Fraction(1, 2)
        duration = min(default_duration, target_end - start)
        if duration > 0:
            completed.append((instrument, start, duration, pitch, onset_velocity))
    completed = sorted(completed, key=lambda row: (row[1], row[0], row[3]))[:max_notes]
    notes = [
        {"id": f"{task}-noto-{index + 1}", "track": tracks_by_instrument[instrument], "start": ftext(start), "duration": ftext(duration), "pitch": pitch, "velocity": velocity}
        for index, (instrument, start, duration, pitch, velocity) in enumerate(completed)
    ]
    patch = {"schema": PATCH_SCHEMA, "base_sha256": seed["sha256"], "ops": [{"op": "insert", "default_policy": "track-neutral-v0", "notes": notes}]}
    diagnostics = {
        "raw_event_count": len(raw_events),
        "note_count": len(notes),
        "query_latency_ms": {
            "minimum": min((row["query_ms"] for row in raw_events), default=0),
            "median": sorted((row["query_ms"] for row in raw_events))[len(raw_events) // 2] if raw_events else 0,
            "maximum": max((row["query_ms"] for row in raw_events), default=0),
        },
        "maximum_quantization_error_beats": max(quantization_errors, default=0),
        "raw_sha256": digest([{key: value for key, value in row.items() if key != "query_ms"} for row in raw_events]),
    }
    return patch, diagnostics


def run_notochord(checkpoint: Path, install_root: Path) -> dict[str, Any]:
    import appdirs
    import importlib.metadata
    import psutil
    import torch

    data_dir = install_root / "data"
    appdirs.user_data_dir = lambda *args, **kwargs: str(data_dir)
    from notochord import Notochord

    process = psutil.Process()
    rss_before = process.memory_info().rss
    started = time.perf_counter()
    model = Notochord.from_checkpoint(checkpoint)
    startup_ms = (time.perf_counter() - started) * 1000
    rss_loaded = process.memory_info().rss
    cohort = make_cohort()
    task_rows = {}
    repeat_hashes = {}
    deterministic_matches = 0
    started = time.perf_counter()
    for index, task in enumerate(TASKS):
        patch, diagnostics = notochord_task(model, task, cohort, 6100 + index)
        repeated_patch, repeated_diagnostics = notochord_task(model, task, cohort, 6100 + index)
        repeat_hashes[task] = [digest(patch), digest(repeated_patch)]
        deterministic_matches += int(patch == repeated_patch and diagnostics["raw_sha256"] == repeated_diagnostics["raw_sha256"])
        task_rows[task] = {"status": "complete", "patch": patch, "explanation": "Notochord received the same MIDI seed prefix. It received no reference excerpt or extracted structure."}
        task_rows[task]["diagnostics"] = diagnostics
    inference_ms = (time.perf_counter() - started) * 1000
    result = {"schema": SCHEMA, "arm": "notochord", "reference_coverage": coverage_for_arm("notochord", cohort), "results": task_rows}
    validation = validate_result(result, "notochord", cohort)
    checkpoint_hash = hashlib.sha256(checkpoint.read_bytes()).hexdigest()
    return {
        "schema": SCHEMA,
        "provider": "notochord",
        "model": "notochord_lakh_50G_deep.pt",
        "package_version": importlib.metadata.version("notochord"),
        "torch_version": torch.__version__,
        "checkpoint_sha256": checkpoint_hash,
        "checkpoint_bytes": checkpoint.stat().st_size,
        "install_bytes": directory_bytes(install_root / ".venv"),
        "platform": f"{platform.system()} {platform.release()} {platform.machine()}",
        "startup_ms": startup_ms,
        "inference_ms": inference_ms,
        "rss_before_bytes": rss_before,
        "rss_loaded_bytes": rss_loaded,
        "rss_model_delta_bytes": max(0, rss_loaded - rss_before),
        "deterministic_tasks": deterministic_matches,
        "deterministic_task_total": len(TASKS),
        "repeat_hashes": repeat_hashes,
        "gate": notochord_gate(),
        "result": result,
        "validation": validation,
    }


