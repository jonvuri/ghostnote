def canonical(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def digest(value: Any) -> str:
    return hashlib.sha256(canonical(value).encode()).hexdigest()


def frac(value: str | int | Fraction) -> Fraction:
    return value if isinstance(value, Fraction) else Fraction(str(value))


def ftext(value: str | int | Fraction) -> str:
    result = frac(value)
    return str(result.numerator) if result.denominator == 1 else f"{result.numerator}/{result.denominator}"


def note(note_id: str, track: str, start: str | int, duration: str | int, pitch: int, velocity: int, channel: int) -> dict[str, Any]:
    return base.note(note_id, track, start, duration, pitch, velocity, channel=channel)


def clip(clip_id: str, length: int, tracks: list[dict[str, Any]], notes: list[dict[str, Any]], harmony: list[dict[str, Any]]) -> dict[str, Any]:
    result = {
        "id": clip_id,
        "meter": "4/4",
        "length_beats": length,
        "tracks": tracks,
        "harmony": harmony,
        "permission": PERMISSION,
        "ownership_basis": "Generated by the phase 6g probe. It contains no third-party notes.",
        "coverage": {"start_beats": "0", "end_beats": str(length), "tracks_complete": True, "notes_complete": True},
        "notes": sorted(notes, key=lambda row: (frac(row["start"]), row["track"], row["pitch"], row["id"])),
    }
    result["sha256"] = digest(result)
    return result


def repeated_notes(prefix: str, track: str, channel: int, starts: list[Fraction], pitches: list[int], velocities: list[int], duration: Fraction = Fraction(1, 2)) -> list[dict[str, Any]]:
    return [
        note(f"{prefix}-{index + 1}", track, start, duration, pitch, velocities[index % len(velocities)], channel)
        for index, (start, pitch) in enumerate(zip(starts, pitches))
    ]


