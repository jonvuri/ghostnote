def coverage_for_arm(arm: str, cohort: dict[str, Any]) -> dict[str, Any]:
    rows = {}
    for reference_id, item in cohort["references"].items():
        if arm in {"seed-only", "notochord"}:
            rows[reference_id] = {"form": "none", "coverage": None, "sha256": item["sha256"], "permission": item["permission"]}
        elif arm == "raw-reference":
            rows[reference_id] = {"form": "raw compact bars", "coverage": item["coverage"], "sha256": item["sha256"], "permission": item["permission"]}
        elif arm == "extracted-structure":
            rows[reference_id] = {"form": "extracted structure", "coverage": item["coverage"], "sha256": item["sha256"], "permission": item["permission"]}
        else:
            rows[reference_id] = {"form": "extracted structure plus first-bar excerpt", "coverage": {"structure": item["coverage"], "excerpt": {"start_beats": "0", "end_beats": "4"}}, "sha256": item["sha256"], "permission": item["permission"]}
