def render_bar(item: dict[str, Any], coverage_end: Fraction | None = None) -> str:
    end = frac(item["length_beats"]) if coverage_end is None else coverage_end
    lines = [
        f"score {item['id']} hash={item['sha256']} meter={item['meter']} length={item['length_beats']}b",
        f"permission={item['permission']} coverage=[0,{ftext(end)}) complete={str(coverage_end is None).lower()}",
    ]
    lines.extend(f"track {row['id']} role={row['role']} voice={row['voice']}" for row in item["tracks"])
    lines.extend(f"harmony at={row['start']} symbol={row['symbol']}" for row in item["harmony"] if frac(row["start"]) < end)
    for row in item["notes"]:
        if frac(row["start"]) >= end:
            continue
        bar_number = int(frac(row["start"]) // 4) + 1
        offset = frac(row["start"]) % 4
        lines.append(f"{row['id']} {row['track']} b{bar_number}+{ftext(offset)} dur={row['duration']} p{row['pitch']} v{row['velocity']}")
    return "\n".join(lines)


def structure(item: dict[str, Any]) -> dict[str, Any]:
    role_by_track = {row["id"]: row["role"] for row in item["tracks"]}
    grouped: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in item["notes"]:
        grouped[role_by_track[row["track"]]].append(row)
    roles = {}
    for role, notes in sorted(grouped.items()):
        by_bar = Counter(int(frac(row["start"]) // 4) + 1 for row in notes)
        onsets = sorted({ftext(frac(row["start"]) % 4) for row in notes}, key=frac)
        velocities = [row["velocity"] for row in notes]
        pitches = [row["pitch"] for row in sorted(notes, key=lambda value: frac(value["start"]))]
        roles[role] = {
            "active_bars": sorted(by_bar),
            "notes_per_bar": {str(key): value for key, value in sorted(by_bar.items())},
            "onsets_mod_bar": onsets,
            "accent_threshold": 90,
            "accent_onsets_mod_bar": sorted({ftext(frac(row["start"]) % 4) for row in notes if row["velocity"] >= 90}, key=frac),
            "median_velocity": sorted(velocities)[len(velocities) // 2],
            "pitch_interval_signs": [int(second > first) - int(second < first) for first, second in zip(pitches, pitches[1:])],
            "pitch_span": max(pitches) - min(pitches),
        }
    harmony_starts = [row["start"] for row in item["harmony"]]
    return {"source_id": item["id"], "source_sha256": item["sha256"], "coverage": item["coverage"], "permission": item["permission"], "harmony_change_beats": harmony_starts, "roles": roles}


