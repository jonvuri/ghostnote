def render_context(arm: str, cohort: dict[str, Any]) -> str:
    blocks = ["SEEDS"]
    blocks.extend(render_bar(item) for item in cohort["seeds"].values())
    blocks.append("REFERENCES")
    if arm == "seed-only":
        blocks.append("No reference content is available. Do not claim a reference trait.")
    elif arm == "raw-reference":
        blocks.extend(render_bar(item) for item in cohort["references"].values())
    elif arm == "extracted-structure":
        blocks.extend(canonical(structure(item)) for item in cohort["references"].values())
    else:
        for item in cohort["references"].values():
            blocks.append(canonical(structure(item)))
            blocks.append("SELECTED EXCERPT\n" + render_bar(item, Fraction(4)))
    return "\n\n".join(blocks)


